// Helper to generate dates backwards from a reference date
function generateSeries(baseDate: string, days: number, startVal: number, volatility: number, trend = 0): [string, number][] {
  const pts: [string, number][] = [];
  let cur = startVal;
  const ref = new Date(baseDate + 'T00:00:00Z').getTime();
  for (let i = days; i >= 0; i--) {
    const d = new Date(ref - i * 864e5).toISOString().slice(0, 10);
    // Add realistic pseudo-random walk based on date hash
    const hash = Math.sin(i * 12.9898 + startVal) * 43758.5453;
    const rnd = (hash - Math.floor(hash)) * 2 - 1;
    cur = cur * (1 + (trend + rnd * volatility));
    pts.push([d, Number(cur.toFixed(4))]);
  }
  return pts;
}

